// English build of the install guide design (vande #036).
//
// The design ships in Vietnamese only, as raw HTML plus the design's own
// script (ig-*-html.ts / ig-*-script.ts). This writes their English twins
// (*.en.ts) by swapping every Vietnamese text run — the text between tags and
// quotes — for its entry in ig-en.json, so markup and behaviour stay exactly
// the design's. Run after changing a design file or the dictionary:
//
//   node components/layout/sections/install-guide/design/gen-en.mjs
//
// It fails, writing nothing, if any Vietnamese text has no English entry.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const dict = JSON.parse(readFileSync(join(dir, "ig-en.json"), "utf8"));
const VIET = /[À-ỹđĐ]/;
// Text runs are cut at tags, quotes and string escapes (\n, \", \\).
const DELIM = /(\\[nrt"\\]|[<>'"])/;
const FILES = ["ig-desktop-html", "ig-mobile-html", "ig-desktop-script", "ig-mobile-script"];

const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

function translate(src, name) {
  let out = src;
  for (const [vi, en] of dict.context) out = out.split(vi).join(en);
  const missing = new Set();
  out = out
    .split(DELIM)
    .map((part, i) => {
      if (i % 2 === 1) return part; // a delimiter
      const text = part.trim();
      if (!text || !VIET.test(text)) return part;
      const en = dict.text[text];
      if (en === undefined) {
        // Comments may stay Vietnamese; everything a visitor sees may not.
        if (stripComments(src).includes(text)) missing.add(text);
        return part;
      }
      return part.replace(text, () => en);
    })
    .join("");
  if (missing.size) throw new Error(`${name}: no English for\n  ${[...missing].join("\n  ")}`);
  return out;
}

const results = FILES.map((name) => {
  const src = readFileSync(join(dir, `${name}.ts`), "utf8");
  const en = translate(src, name)
    .replace("// Generated from the #065 design file by the port script — do not edit by hand.",
      "// English build of the #065 design file (vande #036): generated by gen-en.mjs\n// from the Vietnamese file next to it and ig-en.json — do not edit by hand.");
  const left = stripComments(en).split(DELIM).filter((p, i) => i % 2 === 0 && VIET.test(p));
  if (left.length) throw new Error(`${name}: Vietnamese left over: ${left.slice(0, 5).join(" | ")}`);
  return [join(dir, `${name}.en.ts`), en];
});
for (const [path, text] of results) writeFileSync(path, text);
console.log(`wrote ${results.length} English files`);
